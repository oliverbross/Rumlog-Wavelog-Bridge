@Test func bridgeFileStorePersistsSettingsAndBootstrapSeparately() async throws {
    let directory = FileManager.default.temporaryDirectory
        .appendingPathComponent("bridge-store-\(UUID().uuidString)", isDirectory: true)
    defer { try? FileManager.default.removeItem(at: directory) }
    let store = try BridgeFileStore(directoryURL: directory)
    var settings = BridgeSettings()
    settings.stationID = 2
    settings.stationName = "Darwin NT"
    try await store.saveSettings(settings)
    try await store.saveBootstrapState(BootstrapState(
        stationID: 2,
        nextPage: 4,
        importedCount: 1_500,
        totalCount: 2_000,
        lastFetchedID: 99
    ))

    #expect(try await store.loadSettings() == settings)
    let progress = try await store.loadBootstrapState(stationID: 2)
    #expect(progress.nextPage == 4)
    #expect(progress.importedCount == 1_500)
    #expect(try await store.loadBootstrapState(stationID: 1).importedCount == 0)
    let continuous = ContinuousSyncState(
        stationID: 2,
        lastWavelogID: 99,
        knownFingerprints: ["abc"]
    )
    try await store.saveContinuousSyncState(continuous)
    #expect(try await store.loadContinuousSyncState(stationID: 2) == continuous)
    #expect(try await store.loadContinuousSyncState(stationID: 1).knownFingerprints.isEmpty)
}

@Test(.enabled(if: ProcessInfo.processInfo.environment["RUN_RUMLOG_INTEGRATION"] == "1"))
func readsFromRunningRumlogViaSupportedAppleEvent() async throws {
    let client = RumlogAppleEventClient()
    #expect(client.isInstalled())
    #expect(client.isRunning())
    let adif = try await Task.detached {
        try client.exportADIF(since: "1970-01-01 00:00:00")
    }.value
    print("RUMLOG_READ_RECORDS=\(ADIFParser().records(in: adif).count)")
    #expect(adif.isEmpty || adif.uppercased().contains("ADIF") || adif.uppercased().contains("EOH"))
}

@Test(.enabled(if: ProcessInfo.processInfo.environment["RUN_LIVE_BOOTSTRAP"] == "1"))
func importsOneLiveWavelogContactIntoOpenRumlog() async throws {
    let environment = ProcessInfo.processInfo.environment
    let token = try #require(environment["WAVELOG_TOKEN"])
    let baseURL = try #require(URL(string: environment["WAVELOG_URL"] ?? ""))
    let stationID = try #require(Int(environment["WAVELOG_STATION_ID"] ?? ""))
    let wavelog = WavelogClient(configuration: try WavelogConfiguration(
        baseURL: baseURL,
        token: token,
        stationID: stationID
    ))
    let page = try await wavelog.exportADIF(page: 1, perPage: 1)
    #expect(page.data.exported == 1)

    let rumlog = RumlogAppleEventClient()
    try await Task.detached { try rumlog.importADIF(page.data.adif) }.value
    let exported = try await Task.detached {
        try rumlog.exportADIF(since: "1970-01-01 00:00:00")
    }.value
    let records = ADIFParser().records(in: exported)
    let calls = records.prefix(3).compactMap { $0["CALL"] }.joined(separator: ",")
    print("RUMLOG_EXPORT_RECORDS=\(records.count) CALLS=\(calls)")
    #expect(records.count >= 1)
}
