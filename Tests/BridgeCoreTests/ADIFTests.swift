@Test func parsesADIFAndMapsWavelogCreate() throws {
    let adif = """
    Generated by a logger
    <ADIF_VER:5>3.1.7
    <EOH>
    <CALL:6>VK8ABC<BAND:3>20M<MODE:2>FT<QSO_DATE:8>20261004<TIME_ON:6>102030<FREQ:9>14.074000<RST_SENT:3>-10<RST_RCVD:3>-08<GRIDSQUARE:6>PH57aa<EOR>
    """
    let records = ADIFParser().records(in: adif)
    let record = try #require(records.first)
    #expect(records.count == 1)
    #expect(record["CALL"] == "VK8ABC")

    let create = try #require(WavelogQSOCreate(adif: record))
    #expect(create.qsoDate == "2026-10-04")
    #expect(create.timeOn == "102030")
    #expect(create.frequency == 14_074_000)
    #expect(create.gridSquare == "PH57aa")
    #expect(record.adifDocument.contains("<CALL:6>VK8ABC"))
    #expect(record.adifDocument.hasSuffix("<EOR>\r\n"))
}

@Test func filtersKnownADIFRecordWithoutReencodingRemainingRecord() throws {
    let first = "<CALL:3>AAA<BAND:3>20M<MODE:2>CW<QSO_DATE:8>20260101<TIME_ON:6>010203<FREQ:6>14.050<EOR>"
    let second = "<CALL:3>BBB<BAND:3>40M<MODE:3>SSB<QSO_DATE:8>20260102<TIME_ON:6>040506<FREQ:5>7.100<EOR>"
    let adif = "header<EOH>\r\n\(first)\r\n\(second)\r\n"
    let parser = ADIFParser()
    let known = try #require(parser.records(in: first).first?.semanticIdentityHash)
    let filtered = parser.removingKnownRecords(from: adif, knownFingerprints: [known])
    #expect(filtered.records.count == 1)
    #expect(filtered.records.first?["CALL"] == "BBB")
    #expect(!filtered.adif.contains(first))
    #expect(filtered.adif.contains(second))
}

@Test func semanticIdentityIgnoresFrequencyFormattingZeros() {
    let compact = SemanticQSOIdentity(
        call: "9H1CJ",
        timestamp: "20221008150236",
        band: "15m",
        mode: "SSB",
        frequency: "21.3178"
    )
    let padded = SemanticQSOIdentity(
        call: "9h1cj",
        timestamp: "20221008150236",
        band: "15M",
        mode: "ssb",
        frequency: "21.317800"
    )
    #expect(compact == padded)
    #expect(compact.sha256 == padded.sha256)
}

